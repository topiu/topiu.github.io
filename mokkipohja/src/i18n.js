export function tr(lang, key) {
  const d = STR[lang] || STR.en;
  if (key.includes(".")) {
    const [a, b] = key.split(".");
    return (d[a] && d[a][b]) || (STR.en[a] && STR.en[a][b]) || b;
  }
  return d[key] ?? STR.en[key] ?? key;
}
export const nameOf = (def, lang) => (def.key ? tr(lang, "f." + def.key) : def.name);
export const groupOf = (def, lang) =>
  def.groupKey ? tr(lang, "g." + def.groupKey) : def.group || tr(lang, "g.custom");
